/** Build only: no connection, credentials, provider calls or automatic deployment. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const jsonPath = new URL('./sql/seeds/p1-study-days-4-7.json', import.meta.url);
const sqlPath = new URL('./sql/seeds/p1-study-days-4-7.sql', import.meta.url);
const content = JSON.stringify(JSON.parse(readFileSync(jsonPath, 'utf8')), null, 2);
if (content.includes('$studies$')) throw new Error('Reserved SQL delimiter in editorial content');
const sql = `-- Generated by scripts/build-p1-study-seed.mjs; edit the adjacent JSON source.
-- Additive DRAFTS, layer 1, days 4-7. No production publication or schema changes.
-- Requires migrations through 202610160112. Run in an isolated database first.
BEGIN;
SET LOCAL search_path = pg_catalog;
DO $seed$
DECLARE
  item jsonb;
  refs text[];
  cache_identity text;
  existing public.lab_v2_study_content%ROWTYPE;
  items jsonb := $studies$${content}$studies$::jsonb;
BEGIN
  FOR item IN SELECT value FROM pg_catalog.jsonb_array_elements(items) LOOP
    SELECT array_agg(value ORDER BY ord) INTO refs
      FROM pg_catalog.jsonb_array_elements_text(item->'chapter_refs') WITH ORDINALITY AS r(value, ord);
    -- Psalm 3 belongs to day 5 in 365-day plans and day 6 in 366-day plans.
    -- Accept only an ordered subset of at least one actual plan for this day.
    IF NOT EXISTS (
      SELECT 1 FROM public.lab_v2_plan_chapters p
      WHERE p.day_number = (item->>'journey_day')::integer AND p.plan_length IN (365, 366)
        AND p.chapter_id = ANY(refs)
      GROUP BY p.plan_length
      HAVING array_agg(p.chapter_id ORDER BY p.slot) = refs
    ) THEN RAISE EXCEPTION 'Study references do not match an annual plan: %', item->>'study_key'; END IF;
    cache_identity := 'bible-annual:' || (item->>'journey_day') || ':'
      || array_to_string(refs, ',') || ':L1:2026-10-p1-v1';
    SELECT * INTO existing FROM public.lab_v2_study_content WHERE study_key = item->>'study_key';
    IF FOUND AND (existing.content IS DISTINCT FROM item->'content'
      OR existing.cache_key IS DISTINCT FROM cache_identity
      OR existing.chapter_refs IS DISTINCT FROM refs
      OR existing.journey_day IS DISTINCT FROM (item->>'journey_day')::smallint
      OR existing.layer <> 1 OR existing.source_kind <> 'curated'
      OR existing.journey_key <> 'bible-annual'
      OR existing.content_version <> '2026-10-p1-v1'
      OR existing.provider_model IS NOT NULL
      OR existing.title IS DISTINCT FROM item->'content'->>'title')
    THEN RAISE EXCEPTION 'Refusing to overwrite different study content: %', item->>'study_key'; END IF;
    IF EXISTS(SELECT 1 FROM public.lab_v2_study_catalog
      WHERE study_key = item->>'study_key'
        AND (title IS DISTINCT FROM item->'content'->>'title' OR xp <> 15))
    THEN RAISE EXCEPTION 'Refusing to overwrite different study catalog: %', item->>'study_key'; END IF;
    INSERT INTO public.lab_v2_study_catalog(study_key, title, xp)
    VALUES(item->>'study_key', item->'content'->>'title', 15)
    ON CONFLICT (study_key) DO NOTHING;
    INSERT INTO public.lab_v2_study_content
      (study_key, journey_key, journey_day, chapter_refs, layer, content_version,
       cache_key, source_kind, publication_status, title, content, provider_model)
    VALUES(item->>'study_key', 'bible-annual', (item->>'journey_day')::smallint, refs,
      1, '2026-10-p1-v1', cache_identity, 'curated', 'draft',
      item->'content'->>'title', item->'content', NULL)
    ON CONFLICT (study_key) DO NOTHING;
  END LOOP;
END $seed$;
COMMIT;
`;
if (process.argv.includes('--check')) {
  if (readFileSync(sqlPath, 'utf8') !== sql) throw new Error('Study SQL is stale; rebuild from JSON');
  console.log('PASS: SQL matches editorial JSON');
} else {
  writeFileSync(sqlPath, sql);
  console.log(`Generated ${fileURLToPath(sqlPath)}`);
}
