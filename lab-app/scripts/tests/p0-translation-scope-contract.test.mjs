import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const root=new URL("../../",import.meta.url);
const source=(path)=>readFileSync(new URL(path,root),"utf8");
const rights=source("supabase/migrations/202611010001_almeida_kjv_public_only.sql");
const provenance=source("supabase/migrations/202611010002_strong_stepbible_provenance.sql");
const query=source("supabase/migrations/202611010003_strong_lexicon_two_tier_rpc.sql");
const app=source("src/features/bible.ts");
const lex=source("src/features/strong-lexicon.ts");
const drawer=source("src/components/StrongLexiconDrawer.tsx");
const backfill=source("scripts/sql/releases/01-strong-stepbible-provenance-20261101.sql");
const release=source("scripts/sql/releases/02-strong-publication-after-restore-20261101.sql");
const qa=source("scripts/sql/releases/03-strong-portuguese-auto-qa-20261101.sql");
test("reader exposes only Almeida 1911 and English KJV",()=>{
 assert.match(app,/PUBLIC_BIBLE_EDITIONS=Object\.freeze\(\["ALM1911","KJV"\]/);
 assert.match(app,/isPublicBibleEdition\(e\.code\)&&e\.available/);
 assert.match(app,/validateEdition\(edition\)/);
 assert.match(rights,/where code in \('NVI','NAA','ARA','NTLH'\)/i);
 assert.match(rights,/rights_evidence_url=null/i);
 assert.doesNotMatch(rights,/DELETE\s+FROM\s+public\.lab_bible_/i);
});
test("Strong provenance, RLS and source releases are separate from editorial approval",()=>{
 assert.match(provenance,/source_verified_stepbible/);
 assert.match(provenance,/editorial_reviewed/);
 assert.match(provenance,/default false/);
 assert.match(provenance,/reviewed_at is not null/);
 assert.match(provenance,/rights_status='public_domain'/);
 assert.match(query,/security invoker/i);
 assert.match(query,/auth\.uid\(\)/);
 assert.match(query,/v\.review_status in \('source_verified_stepbible','editorial_reviewed'\)/);
 assert.match(query,/tr\.auto_qa_passed=true/);
 assert.match(query,/lr\.publication_status='published'/);
 assert.match(query,/tag\.publication_status='published'/);
 assert.match(query,/v\.edition='KJV'/);
 assert.match(query,/revoke all on function[\s\S]+from public, anon, authenticated/);
 assert.doesNotMatch(query,/security definer|insert into|delete from|update public\./i);
 assert.match(backfill,/446231/);
 assert.match(backfill,/1ac5d58521521f62ada6528b953c42fb35875e5952af8d5dc494c6141b1f0620/);
 assert.doesNotMatch(backfill,/set review_status='editorial_reviewed'/i);
 assert.match(release,/Not all source tags verified/i);
});
test("Automated Portuguese glosses retain machine status with explicit disclosure",()=>{
 assert.match(lex,/link_review_status/);
 assert.match(drawer,/não equivale a revisão exegética individual/);
 assert.match(drawer,/Não revisada por humano/);
 assert.match(drawer,/STEP Bible/);
 assert.match(qa,/translation_status='machine'/);
 assert.match(qa,/auto_qa_passed=true/);
 assert.doesNotMatch(qa,/reviewed_at\s*=|translation_status='reviewed'/i);
});
