CREATE OR REPLACE FUNCTION public.lab_game_sync()
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=''
AS $$
DECLARE
 v_user uuid := auth.uid();
 v_today date := (now() AT TIME ZONE 'America/Sao_Paulo')::date;
 v_run public.lab_game_runs%ROWTYPE;
 v_stats public.lab_game_stats%ROWTYPE;
 v_day integer;
 v_checked jsonb;
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Faça login para participar'; END IF;
 -- Serialize all game updates per user by locking stats first.
 INSERT INTO public.lab_game_stats(user_id) VALUES(v_user) ON CONFLICT DO NOTHING;
 SELECT * INTO v_stats FROM public.lab_game_stats WHERE user_id=v_user FOR UPDATE;
 SELECT * INTO v_run FROM public.lab_game_runs
  WHERE user_id=v_user AND status='active' FOR UPDATE;
 IF FOUND AND v_today>v_run.started_on+v_run.completed_days THEN
  UPDATE public.lab_game_runs SET status='failed',finished_on=v_today WHERE id=v_run.id;
  v_run.id := NULL;
 END IF;
 IF v_run.id IS NULL THEN
  INSERT INTO public.lab_game_runs(user_id,started_on)
  VALUES(v_user,v_today) RETURNING * INTO v_run;
 END IF;
 v_day:=v_today-v_run.started_on+1;
 SELECT COALESCE(jsonb_agg(chapter_id ORDER BY chapter_id),'[]'::jsonb)
 INTO v_checked FROM public.lab_game_chapter_checks
 WHERE run_id=v_run.id AND day_number=v_day;
 RETURN jsonb_build_object(
  'run_id',v_run.id,'day',v_day,'completed_days',v_run.completed_days,
  'best_days',v_stats.best_days,'total_xp',v_stats.total_xp,
  'total_completed_days',v_stats.total_completed_days,
  'display_name',v_stats.display_name,
  'leaderboard_opt_in',v_stats.leaderboard_opt_in,
  'checked',v_checked,'today',v_today,
  'finished',v_run.status='completed'
 );
END;$$;
REVOKE ALL ON FUNCTION public.lab_game_sync() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.lab_game_sync() TO authenticated;

CREATE OR REPLACE FUNCTION public.lab_game_confirm_chapter(p_chapter_id text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=''
AS $$
DECLARE
 v_user uuid:=auth.uid();
 v_today date:=(now() AT TIME ZONE 'America/Sao_Paulo')::date;
 v_run public.lab_game_runs%ROWTYPE;
 v_day integer; v_expected integer; v_have integer; v_new integer;
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Autenticação necessária'; END IF;
 PERFORM public.lab_game_sync();
 SELECT * INTO v_run FROM public.lab_game_runs
  WHERE user_id=v_user AND status='active' FOR UPDATE;
 v_day:=v_today-v_run.started_on+1;
 IF v_day<1 OR v_day>365 OR v_day<>v_run.completed_days+1 THEN
  IF EXISTS(SELECT 1 FROM public.lab_game_chapter_checks
   WHERE run_id=v_run.id AND day_number=v_day AND chapter_id=p_chapter_id)
  THEN RETURN public.lab_game_sync(); END IF;
  RAISE EXCEPTION 'Etapa ainda não disponível ou já concluída';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM public.lab_game_plan_chapters
  WHERE version=1 AND day_number=v_day AND chapter_id=p_chapter_id)
 THEN RAISE EXCEPTION 'Este capítulo não pertence à leitura de hoje'; END IF;
 INSERT INTO public.lab_game_chapter_checks(run_id,day_number,chapter_id,read_on)
 VALUES(v_run.id,v_day,p_chapter_id) ON CONFLICT DO NOTHING;
 GET DIAGNOSTICS v_new=ROW_COUNT;
 IF v_new>0 THEN
  UPDATE public.lab_game_stats SET total_xp=total_xp+10,updated_at=now()
  WHERE user_id=v_user;
 END IF;
 SELECT COUNT(*) INTO v_have FROM public.lab_game_chapter_checks
  WHERE run_id=v_run.id AND day_number=v_day;
 SELECT COUNT(*) INTO v_expected FROM public.lab_game_plan_chapters
  WHERE version=1 AND day_number=v_day;
 IF v_have=v_expected AND v_run.completed_days<v_day THEN
  UPDATE public.lab_game_runs
   SET completed_days=v_day,
       status=CASE WHEN v_day=365 THEN 'completed' ELSE 'active' END,
       finished_on=CASE WHEN v_day=365 THEN v_today ELSE NULL END
   WHERE id=v_run.id;
  UPDATE public.lab_game_stats SET
   best_days=GREATEST(best_days,v_day),
   total_completed_days=total_completed_days+1,
   updated_at=now() WHERE user_id=v_user;
 END IF;
 -- Return final success without auto-creating a new run on stage 365.
 IF v_day=365 AND v_have=v_expected THEN
  RETURN jsonb_build_object('run_id',v_run.id,'day',365,'completed_days',365,
   'finished',true,'checked',(SELECT jsonb_agg(chapter_id) FROM public.lab_game_chapter_checks WHERE run_id=v_run.id AND day_number=365),
   'best_days',365,
   'total_xp',(SELECT total_xp FROM public.lab_game_stats WHERE user_id=v_user));
 END IF;
 RETURN public.lab_game_sync();
END;$$;
REVOKE ALL ON FUNCTION public.lab_game_confirm_chapter(text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.lab_game_confirm_chapter(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.lab_game_update_profile(p_name text,p_opt_in boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $$
DECLARE v_user uuid:=auth.uid();v_name text:=btrim(p_name);
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Autenticação necessária'; END IF;
 IF length(v_name)<2 OR length(v_name)>60 THEN RAISE EXCEPTION 'Nome deve ter de 2 a 60 caracteres'; END IF;
 INSERT INTO public.lab_game_stats(user_id,display_name,leaderboard_opt_in)
 VALUES(v_user,v_name,COALESCE(p_opt_in,false))
 ON CONFLICT(user_id) DO UPDATE SET
  display_name=EXCLUDED.display_name,
  leaderboard_opt_in=EXCLUDED.leaderboard_opt_in,updated_at=now();
END;$$;
REVOKE ALL ON FUNCTION public.lab_game_update_profile(text,boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.lab_game_update_profile(text,boolean) TO authenticated;

CREATE OR REPLACE FUNCTION public.lab_game_group_ranking(p_group_id uuid)
RETURNS TABLE(participant text,completed_days integer,best_days integer,total_xp integer)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $$
BEGIN
 IF auth.uid() IS NULL OR NOT EXISTS(
  SELECT 1 FROM public.reading_group_members m
  WHERE m.group_id=p_group_id AND m.user_id=auth.uid()
 ) THEN RAISE EXCEPTION 'Acesso ao grupo não autorizado'; END IF;
 RETURN QUERY SELECT s.display_name,s.total_completed_days,s.best_days::integer,s.total_xp
 FROM public.reading_group_members m
 JOIN public.lab_game_stats s ON s.user_id=m.user_id
 WHERE m.group_id=p_group_id AND s.leaderboard_opt_in=true
 ORDER BY s.best_days DESC,s.total_completed_days DESC,s.total_xp DESC,s.display_name ASC
 LIMIT 100;
END;$$;
REVOKE ALL ON FUNCTION public.lab_game_group_ranking(uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.lab_game_group_ranking(uuid) TO authenticated;
